export const DICTS: Record<Lang, Dict> = { en, tl };

// ---- dates ----
const WEEKDAYS: Record<Lang, string[]> = {
  en: ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"],
  tl: ["Linggo", "Lunes", "Martes", "Miyerkules", "Huwebes", "Biyernes", "Sabado"],
};
const MONTHS: Record<Lang, string[]> = {
  en: ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"],
  tl: ["Ene", "Peb", "Mar", "Abr", "May", "Hun", "Hul", "Ago", "Set", "Okt", "Nob", "Dis"],
};

// "2026-10-14" -> "Wednesday, 14 Oct" (or "Miyerkules, 14 Okt").
export function dayLabel(ymd: string | null | undefined, lang: Lang): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})/.exec(ymd ?? "");
  if (!m) return ymd ?? "";
  const d = new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, Number(m[3])));
  return `${WEEKDAYS[lang][d.getUTCDay()]}, ${d.getUTCDate()} ${MONTHS[lang][d.getUTCMonth()]}`;
}

// Photo caption "SO-1001 · 13 Oct · 09:20 · Delivered" (date and time in Manila) from payload photo metadata.
export function photoCaption(meta: Pick<PhotoMeta, "so_number" | "captured_at" | "kind">, lang: Lang): string {
  const t = DICTS[lang];
  const p = manilaParts(meta.captured_at);
  const k = String(meta.kind ?? "").toLowerCase();
  const result = k === "delivered" ? t.stateDelivered : k === "partial" ? t.partial : k === "failed" ? t.failed : k === "problem" ? t.problemKind : "";
  return [meta.so_number ?? "", p ? `${p.day} ${MONTHS[lang][p.month]}` : "", p?.time ?? "", result].filter(Boolean).join(" · ");
}

// ---- store ----
const KEY = "rgf.driver.lang";

function readStored(): Lang {
  try {
    const v = window.localStorage.getItem(KEY);
    return v === "tl" ? "tl" : "en";
  } catch {
    return "en";
  }
}

let current: Lang | null = null;
const listeners = new Set<() => void>();

export function getLang(): Lang {
  if (current === null) current = typeof window === "undefined" ? "en" : readStored();
  return current;
}

export function setLang(lang: Lang) {
  current = lang;
  try {
    window.localStorage.setItem(KEY, lang);
  } catch {
    // private mode / blocked storage: the choice lasts for this visit only
  }
  try {
    document.documentElement.lang = lang === "tl" ? "fil" : "en";
  } catch {
    // ignore
  }
  listeners.forEach((l) => l());
}

function subscribe(l: () => void) {
  listeners.add(l);
  return () => {
    listeners.delete(l);
  };
}

export function useLang(): [Lang, (lang: Lang) => void] {
  const lang = useSyncExternalStore(subscribe, getLang, () => "en" as Lang);
  return [lang, setLang];
}

export function useT(): Dict {
  const [lang] = useLang();
  return DICTS[lang];
}

// Translate validation and sync failures without changing server values or admin-authored form labels.
export function driverMessage(message: string | null | undefined, t: Dict = DICTS[getLang()]): string {
 const value = message ?? "";
 if (/order_removed|order was removed/i.test(value)) return t.orderRemovedByDispatch;
 if (/trip_removed|trip was removed/i.test(value)) return t.removedTrip;
 if (/photo|proof of delivery/i.test(value)) return t.needPhoto;
 if (/digit/i.test(value)) return t.digitsOnly;
 if (/invoice|DR number/i.test(value)) return t.needInvoice;
 if (/date and time/i.test(value)) return t.enterDateTime;
 if (/valid date/i.test(value)) return t.enterDate;
 if (/count|0 or more/i.test(value)) return t.enterCount;
 if (/number/i.test(value)) return t.enterNumber;
 if (/option/i.test(value)) return t.pickOption;
 if (/tick/i.test(value)) return t.tickRequired;
 if (/reason/i.test(value)) return t.needReason;
 if (/required/i.test(value)) return t.required;
 if (/fetch|network|offline|signal/i.test(value)) return t.noSignal;
 return getLang() === "tl" ? t.somethingWrong : value;
}
